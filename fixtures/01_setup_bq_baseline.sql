SELECT
  a.region,
  COUNT(DISTINCT a.acc_id) AS accounts,
  COUNT(DISTINCT s.sub_id) AS subscriptions,
  COUNT(m.mrr_event_id) AS mrr_events,
  SUM(m.start_mrr_usd) AS total_starting_mrr,
  SUM(m.expansion_mrr_usd) AS total_expansion_mrr,
  SUM(m.churned_mrr_usd) AS total_churn_mrr,
  ROUND(
    (SUM(m.start_mrr_usd) + SUM(m.expansion_mrr_usd) - SUM(m.churned_mrr_usd))
    / NULLIF(SUM(m.start_mrr_usd), 0),
    4
  ) AS baseline_nrr
FROM `opm-looker-core-demo-instance.sales_analytics_demo.fct_mrr_movements` AS m
JOIN `opm-looker-core-demo-instance.sales_analytics_demo.tbl_subscriptions` AS s
  ON m.sub_id = s.sub_id
JOIN `opm-looker-core-demo-instance.sales_analytics_demo.tbl_accounts_v2` AS a
  ON m.acc_id = a.acc_id
GROUP BY a.region
ORDER BY a.region;
